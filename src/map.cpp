void Map::drawMap(){
    for (std::size_t row {0} ; row < Constants::tiles ; ++row){
        for (std::size_t col {0} ; col < Constants::tiles ; ++col){
            switch (m_map[row][col]){
            case 'Z':
                drawTile(col, row, BROWN);
                break;
            case 'S':
            case 'H':
            case 'D':
            case 'X':
                drawTile(col, row, YELLOW);
            }
        }
    }
}

void drawTile(int posX, int posY, Color color){
    DrawRectangle(posX * Constants::tileWidth, posY * Constants::tileHeigth + Constants::header, Constants::tileWidth, 
        Constants::tileHeigth, color);
}